const LAST_MESSAGE_KEY = "school-guard-portal:last-motivational-message";

function getStoredMessage(): string | null {
  if (typeof window === "undefined") return null;

  try {
    return window.localStorage.getItem(LAST_MESSAGE_KEY);
  } catch {
    return null;
  }
}

function storeMessage(message: string) {
  if (typeof window === "undefined") return;

  try {
    window.localStorage.setItem(LAST_MESSAGE_KEY, message);
  } catch {
    // The message can still be displayed when storage is unavailable.
  }
}

export function getRandomMotivationalMessage(): string {
  const lastMessage = getStoredMessage();
  const availableMessages = MOTIVATIONAL_MESSAGES.filter(
    (message) => message !== lastMessage,
  );
  const message =
    availableMessages[Math.floor(Math.random() * availableMessages.length)] ??
    MOTIVATIONAL_MESSAGES[0];

  storeMessage(message);
  return message;
}
